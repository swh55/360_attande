"""Golden decoder test: synthetic stream -> parser -> FFmpegDecoder -> frames.

Uses REAL H.264 access units generated by ffmpeg, wrapped in the exact Gear360
container layout, then runs the full server-side pipeline. This is the closest
to camera data we can get without the device, and it validates the parser AND
decoder against actual codec payloads.
"""
from __future__ import annotations

import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ.setdefault("GEAR360HUB_DB", str(Path(__file__).parent / ".tmp.db"))

import numpy as np  # noqa: E402

from tests.fixtures import make_synthetic_stream  # noqa: E402


def test_golden_pipeline_real_h264(real_h264_access_units):
    from app.media.decoder import FFmpegDecoder
    from app.stream.parser import Gear360ChunkParser

    aus = real_h264_access_units["aus"]
    w, h = real_h264_access_units["width"], real_h264_access_units["height"]

    stream = make_synthetic_stream(aus, codec=0, width=w, height=h, fps=10.0,
                                   force_first_keyframe=False)
    parser = Gear360ChunkParser()
    frames = parser.feed(stream)
    assert parser.info.width == w
    assert parser.info.codec_name == "h264"
    assert len(frames) >= 4, f"parser produced {len(frames)} frames"

    decoder = FFmpegDecoder(parser.info.codec_name, w, h)
    decoder.start()
    decoded = []
    deadline = time.time() + 12
    try:
        for f in frames:
            decoded.extend(decoder.write(f.payload))
            if len(decoded) >= 3:
                break
            time.sleep(0.03)
        # h264 demuxer needs ~1-2 AU lookahead; keep draining before EOF
        while len(decoded) < 3 and time.time() < deadline:
            decoded.extend(decoder.write(b""))
            time.sleep(0.1)
    finally:
        decoder.close()

    assert len(decoded) >= 3, f"decoder produced {len(decoded)} frames"
    img = decoded[0]
    assert img.shape == (h, w, 3)
    assert img.dtype == np.uint8
    # testsrc has non-flat colorful content; frame must not be uniformly black
    assert img.std() > 5.0


def test_decoder_rejects_unknown_dimensions():
    from app.media.decoder import FFmpegDecoder

    d = FFmpegDecoder("h264", 0, 0)
    try:
        d.start()
        assert False, "should have raised"
    except RuntimeError:
        pass
